import { createFileRoute, Link } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import { z } from "zod";
import { ArrowLeft, Download, FileText } from "lucide-react";
import { format } from "date-fns";
import jsPDF from "jspdf";
import { supabase } from "@/integrations/supabase/client";
import { Button } from "@/components/ui/button";
import { MODELS, type ModelKey } from "@/lib/ckd";
import { deriveRisk, getRecommendations, RISK_STYLES } from "@/lib/recommendations";

export const Route = createFileRoute("/_authenticated/report")({
  head: () => ({ meta: [{ title: "Prediction Report — NephroScan" }] }),
  validateSearch: z.object({ id: z.string() }),
  component: ReportPage,
});

function ReportPage() {
  const { id } = Route.useSearch();
  const { data, isLoading } = useQuery({
    queryKey: ["report", id],
    queryFn: async () => {
      const { data, error } = await supabase
        .from("prediction_history")
        .select("*")
        .eq("id", id)
        .single();
      if (error) throw error;
      return data;
    },
  });

  if (isLoading) return <div className="p-10 text-center text-muted-foreground">Loading report…</div>;
  if (!data) return <div className="p-10 text-center">Report not found.</div>;

  const conf = Number(data.confidence_score);
  const result = (data.prediction_result === "ckd" ? "ckd" : "not_ckd") as "ckd" | "not_ckd";
  const risk = deriveRisk(result, conf);
  const riskStyle = RISK_STYLES[risk];
  const modelName = MODELS[data.selected_model as ModelKey].name;
  const recs = getRecommendations(result, risk, {
    hypertension: data.hypertension,
    diabetes_mellitus: data.diabetes_mellitus,
    hemoglobin: Number(data.hemoglobin),
  });

  const downloadPdf = () => {
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    let y = 18;

    doc.setFontSize(20);
    doc.setTextColor(20, 70, 140);
    doc.text("NephroScan — CKD Prediction Report", 14, y);
    y += 8;
    doc.setDrawColor(220);
    doc.line(14, y, pageWidth - 14, y);
    y += 8;

    doc.setFontSize(10);
    doc.setTextColor(80);
    doc.text(`Report ID: ${data.id}`, 14, y); y += 5;
    doc.text(`Generated: ${format(new Date(data.prediction_timestamp), "PPpp")}`, 14, y); y += 5;
    doc.text(`Model used: ${modelName}`, 14, y); y += 10;

    doc.setFontSize(14);
    doc.setTextColor(0);
    doc.text("Prediction summary", 14, y); y += 7;
    doc.setFontSize(11);
    doc.setTextColor(result === "ckd" ? 180 : 30, result === "ckd" ? 40 : 130, result === "ckd" ? 40 : 60);
    doc.text(`Result: ${result === "ckd" ? "CKD Detected" : "CKD Not Detected"}`, 14, y); y += 6;
    doc.setTextColor(40);
    doc.text(`Confidence: ${conf}%`, 14, y); y += 6;
    doc.text(`Risk level: ${riskStyle.label}`, 14, y); y += 10;

    doc.setFontSize(14);
    doc.setTextColor(0);
    doc.text("Input parameters", 14, y); y += 7;
    doc.setFontSize(10);
    doc.setTextColor(60);
    const rows: [string, string][] = [
      ["Specific gravity", Number(data.specific_gravity).toFixed(3)],
      ["Hemoglobin", `${data.hemoglobin} g/dL`],
      ["RBC count", `${data.red_blood_cell_count} M/cmm`],
      ["Albumin", String(data.albumin)],
      ["Hypertension", data.hypertension ? "Yes" : "No"],
      ["Diabetes mellitus", data.diabetes_mellitus ? "Yes" : "No"],
      ["Appetite", data.appetite],
      ["Pus cell", data.pus_cell],
    ];
    rows.forEach(([k, v]) => {
      doc.text(`${k}:`, 16, y);
      doc.text(v, 80, y);
      y += 5;
    });
    y += 5;

    doc.setFontSize(14);
    doc.setTextColor(0);
    doc.text("Health recommendations", 14, y); y += 7;
    doc.setFontSize(10);
    doc.setTextColor(60);
    recs.forEach((r, i) => {
      if (y > 270) { doc.addPage(); y = 18; }
      doc.setFont("helvetica", "bold");
      doc.text(`${i + 1}. ${r.title}`, 14, y); y += 5;
      doc.setFont("helvetica", "normal");
      const lines = doc.splitTextToSize(r.detail, pageWidth - 28);
      doc.text(lines, 16, y);
      y += lines.length * 5 + 3;
    });

    if (y > 250) { doc.addPage(); y = 18; }
    y += 4;
    doc.setDrawColor(220);
    doc.line(14, y, pageWidth - 14, y);
    y += 6;
    doc.setFontSize(8);
    doc.setTextColor(120);
    const disclaimer = doc.splitTextToSize(
      "Disclaimer: This report is generated by NephroScan, a screening and educational tool. It is not a medical diagnosis. Please consult a qualified healthcare professional before making any clinical decisions.",
      pageWidth - 28,
    );
    doc.text(disclaimer, 14, y);

    doc.save(`nephroscan-report-${data.id.slice(0, 8)}.pdf`);
  };

  return (
    <div className="p-6 md:p-10 max-w-3xl mx-auto space-y-6">
      <Link to="/results" search={{ id }} className="text-sm text-muted-foreground hover:text-foreground inline-flex items-center gap-1">
        <ArrowLeft className="w-4 h-4" /> Back to result
      </Link>

      <div className="rounded-2xl border bg-card p-6 md:p-8 shadow-card">
        <div className="flex items-start justify-between gap-4 flex-wrap">
          <div>
            <div className="inline-flex items-center gap-2 px-2.5 py-1 rounded-full bg-accent text-xs font-medium">
              <FileText className="w-3.5 h-3.5" /> Report preview
            </div>
            <h1 className="text-3xl font-bold tracking-tight mt-3">Prediction Report</h1>
            <p className="text-sm text-muted-foreground mt-1">
              Report ID: <span className="font-mono">{data.id.slice(0, 12)}…</span>
            </p>
            <p className="text-sm text-muted-foreground">
              Generated {format(new Date(data.prediction_timestamp), "PPpp")}
            </p>
          </div>
          <Button onClick={downloadPdf} size="lg" className="shadow-elegant">
            <Download className="w-4 h-4 mr-2" /> Download PDF
          </Button>
        </div>

        <div className="grid sm:grid-cols-3 gap-4 mt-8">
          <Field label="Result" value={result === "ckd" ? "CKD Detected" : "CKD Not Detected"} />
          <Field label="Confidence" value={`${conf}%`} />
          <Field label="Risk level" value={riskStyle.label} />
        </div>

        <h2 className="font-semibold mt-8 mb-3">Input parameters</h2>
        <dl className="grid sm:grid-cols-2 gap-x-6 gap-y-2 text-sm">
          <Row k="Specific gravity" v={Number(data.specific_gravity).toFixed(3)} />
          <Row k="Hemoglobin" v={`${data.hemoglobin} g/dL`} />
          <Row k="RBC count" v={`${data.red_blood_cell_count} M/cmm`} />
          <Row k="Albumin" v={String(data.albumin)} />
          <Row k="Hypertension" v={data.hypertension ? "Yes" : "No"} />
          <Row k="Diabetes" v={data.diabetes_mellitus ? "Yes" : "No"} />
          <Row k="Appetite" v={data.appetite} />
          <Row k="Pus cell" v={data.pus_cell} />
        </dl>

        <h2 className="font-semibold mt-8 mb-3">Health recommendations</h2>
        <ol className="space-y-3 text-sm list-decimal list-inside">
          {recs.map((r) => (
            <li key={r.title}>
              <span className="font-medium text-foreground">{r.title}.</span>{" "}
              <span className="text-muted-foreground">{r.detail}</span>
            </li>
          ))}
        </ol>
      </div>

      <div className="rounded-md bg-warning/10 border border-warning/30 p-4 text-sm">
        <strong>Disclaimer:</strong>{" "}
        This is a screening tool, not a medical diagnosis. Always consult a qualified healthcare professional before making clinical decisions.
      </div>
    </div>
  );
}

function Field({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-lg border bg-background p-4">
      <div className="text-xs text-muted-foreground">{label}</div>
      <div className="text-base font-semibold mt-1">{value}</div>
    </div>
  );
}
function Row({ k, v }: { k: string; v: string }) {
  return (<><dt className="text-muted-foreground">{k}</dt><dd className="font-medium">{v}</dd></>);
}
